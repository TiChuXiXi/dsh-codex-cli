test('Git amend, revert, cherry-pick, reset and write gates operate only on fixture',async t=>{
 const {cwd,call}=await fixture(t)
 await writeFile(join(cwd,'base'),'base');await call('commit',{paths:['base'],message:'base'})
 const base=(await git(cwd,'rev-parse','HEAD')).trim()
 await call('checkout',{ref:'feature',create:true})
 await writeFile(join(cwd,'feature'),'feature');await call('commit',{paths:['feature'],message:'feature'})
 await call('commit',{message:'amended',amend:true})
 const feature=(await git(cwd,'rev-parse','HEAD')).trim()
 await call('checkout',{ref:'main'});await call('cherry-pick',{rev:feature})
 assert.equal(await readFile(join(cwd,'feature'),'utf8'),'feature')
 await call('revert',{rev:'HEAD'});await assert.rejects(readFile(join(cwd,'feature')))
 await call('reset',{rev:base,mode:'soft'})
 assert.equal((await git(cwd,'rev-parse','HEAD')).trim(),base)
 const readonly=createGitService({allowWrite:false});t.after(()=>readonly.dispose())
 await assert.rejects(readonly.call('stage',{cwd,paths:['base']}),e=>e.code==='git-vcs/write-disabled')
 const noDanger=createGitService({allowDangerous:false});t.after(()=>noDanger.dispose())
 await assert.rejects(noDanger.call('reset',{cwd,rev:base,mode:'hard'}),e=>e.code==='git-vcs/dangerous-disabled')
 const noPush=createGitService({allowPush:false});t.after(()=>noPush.dispose())
 await assert.rejects(noPush.call('push',{cwd}),e=>e.code==='git-vcs/push-disabled')
})
