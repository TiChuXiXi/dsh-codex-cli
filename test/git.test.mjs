test('Git empty state, special paths, selected commit leaves other staged content, rename and show',async t=>{
 const {cwd,call}=await fixture(t)
 assert.equal((await call('repo/snapshot',{all:true})).commits.length,0)
 const names=['中文 空格.txt','-leading.txt','tab\tline\n.txt',':(glob)*.txt','other.txt']
 for(const name of names)await writeFile(join(cwd,name),'initial\n')
 await call('stage',{paths:names})
 await call('unstage',{paths:[names[0]]})
 assert.equal((await call('status')).entries.find(e=>e.path===names[0]).untracked,true)
 await call('commit',{paths:[names[0]],message:'selected first'})
 assert.equal((await git(cwd,'-c','core.quotepath=false','show','--pretty=','--name-only','HEAD')).trim(),names[0])
 assert.equal((await call('status')).entries.filter(e=>e.staged).length,4)
 await call('commit',{paths:names.slice(1),message:'remaining'})
 await writeFile(join(cwd,names[0]),'changed\n')
 assert.match((await call('diff',{path:names[0]})).patch,/changed/)
 await rename(join(cwd,names[0]),join(cwd,'renamed.txt'))
 await call('stage',{paths:[names[0],'renamed.txt']})
 const row=(await call('status')).entries.find(e=>e.path==='renamed.txt')
 // Content was changed before rename; Git can classify it as add/delete rather than rename.
 await call('commit',{paths:[names[0],'renamed.txt'],message:'rename'})
 const shown=await call('show',{rev:'HEAD',noPatch:true})
 assert.ok(shown.files.some(f=>f.path==='renamed.txt'))
 const special=await call('show',{rev:'HEAD~1',noPatch:true})
 assert.ok(special.files.some(f=>f.path==='tab\tline\n.txt'))
 assert.match((await call('show/file',{rev:'HEAD~1',path:'-leading.txt'})).patch,/initial/)
 await assert.rejects(call('stage',{paths:['../outside']}),/paths/)
 await assert.rejects(call('diff',{path:'/etc/passwd'}),/path/)
})
test('Git branches, local bare remote fetch/push/pull, stash lifecycle and failure history',async t=>{
 const {cwd,call}=await fixture(t)
 await writeFile(join(cwd,'file.txt'),'one\n')
 await call('commit',{paths:['file.txt'],message:'base'})
 await call('branch/create',{name:'feature'})
 await call('checkout',{ref:'feature'})
 await writeFile(join(cwd,'file.txt'),'two\n')
 await call('stash',{action:'push',message:'saved',includeUntracked:true})
 const stash=(await call('repo/snapshot',{all:true})).stashes[0]
 assert.match((await call('stash/show',{ref:stash.hash})).patch,/two/)
 await call('stash',{action:'apply',ref:stash.ref})
 assert.match(await readFile(join(cwd,'file.txt'),'utf8'),/two/)
 await call('discard',{paths:['file.txt']})
 await call('stash',{action:'pop',ref:stash.ref})
 assert.equal((await call('stash',{action:'list'})).stashes.length,0)
 await call('commit',{paths:['file.txt'],message:'feature'})
 await call('checkout',{ref:'main'})
 await call('merge',{ref:'feature'})
 await call('branch/delete',{name:'feature'})
 const bare=await mkdtemp(join(tmpdir(),'codex-git-bare-'))
 await git(bare,'init','--bare')
 await call('remote/add',{name:'origin',url:bare})
 await call('push',{remote:'origin',branch:'main',setUpstream:true})
 await call('fetch',{remote:'origin'})
 await call('pull')
 assert.equal((await call('repo/snapshot',{all:true})).repo.upstream,'origin/main')
 await assert.rejects(call('checkout',{ref:'missing'}))
 const records=(await call('console/list')).entries
 assert.ok(records.some(e=>e.exitCode!==0))
 assert.ok(records.every(e=>typeof e.durationMs==='number'))
 await call('remote/remove',{name:'origin'})
})
